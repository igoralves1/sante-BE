from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


async def upgrade(db: BaseDBAsyncClient) -> str:
    # Papel só de leitura usado pela ferramenta de consultas (/api/banco/*). Ele só tem SELECT.
    # A API liga o LOGIN e define a senha ao abrir as conexões de consulta (app/routers/banco.py).
    return """
        DO $$
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sante_leitura') THEN
                CREATE ROLE sante_leitura NOLOGIN;
            END IF;
        END $$;
        GRANT USAGE ON SCHEMA public TO sante_leitura;
        GRANT SELECT ON ALL TABLES IN SCHEMA public TO sante_leitura;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO sante_leitura;"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE SELECT ON TABLES FROM sante_leitura;
        REVOKE SELECT ON ALL TABLES IN SCHEMA public FROM sante_leitura;
        REVOKE USAGE ON SCHEMA public FROM sante_leitura;"""


